//! Generated Lean soundness scaffolding.
//!
//! This module only emits the default no-obligation theorem shape. Soundness-domain
//! Anneal annotations are still rejected before this runs, because preconditions,
//! postconditions, and invariants need nontrivial generated obligations.

use anyhow::Context as _;

/// Emits default weak soundness theorems for Aeneas-generated functions.
pub fn write_default_soundness(
    roots: &crate::resolve::LockedRoots,
    packages: &[crate::scanner::AnnealArtifact],
) -> anyhow::Result<()> {
    for artifact in packages {
        let artifact_dir = artifact.lean_dir_path(roots);
        let funs_path = artifact_dir.join("Funs.lean");
        if !funs_path.exists() {
            continue;
        }
        let funs = std::fs::read_to_string(&funs_path)
            .with_context(|| format!("Failed to read {}", funs_path.display()))?;
        let Some(generated) = default_soundness_module(&artifact.artifact_slug(), &funs) else {
            continue;
        };
        let soundness_path = artifact_dir.join("Soundness.lean");
        std::fs::write(&soundness_path, generated)
            .with_context(|| format!("Failed to write {}", soundness_path.display()))?;
    }
    Ok(())
}

fn default_soundness_module(module_name: &str, funs: &str) -> Option<String> {
    let namespace = parse_namespace(funs)?;
    let defs = parse_result_defs(funs);
    if defs.is_empty() {
        return None;
    }

    let mut out = String::new();
    out.push_str("-- THIS FILE WAS AUTOMATICALLY GENERATED BY ANNEAL\n");
    out.push_str("-- Default weak soundness theorems for Aeneas-generated functions.\n");
    out.push_str(&format!("import {module_name}.Funs\n\n"));
    out.push_str("open Aeneas Aeneas.Std Result ControlFlow Error\n");
    out.push_str("open Std.Do\n");
    out.push_str("set_option linter.unusedVariables false\n\n");
    out.push_str(&format!("namespace {namespace}\n\n"));

    for (idx, def) in defs.iter().enumerate() {
        out.push_str(&format!("/-- Default weak soundness theorem for `{}`. -/\n", def.name));
        out.push_str(&format!("theorem anneal_default_soundness_{idx}"));
        if !def.binders.is_empty() {
            out.push(' ');
            out.push_str(&def.binders.join(" "));
        }
        out.push_str(" :\n");
        out.push_str("  ⊢ₛ wp⟦");
        out.push_str(&def.application());
        out.push_str("⟧ post⟨fun _ => ⌜True⌝,\n");
        out.push_str("                fun _ => ⌜True⌝,\n");
        out.push_str("                fun () => ⌜True⌝⟩ := by\n");
        out.push_str("  cases h : ");
        out.push_str(&def.application());
        out.push_str(" <;> simp [WP.wp, PredTrans.apply, h]\n\n");
    }

    out.push_str(&format!("end {namespace}\n"));
    Some(out)
}

fn parse_namespace(funs: &str) -> Option<String> {
    funs.lines()
        .map(str::trim)
        .find_map(|line| line.strip_prefix("namespace ").map(str::trim).map(str::to_string))
}

#[derive(Debug, PartialEq, Eq)]
struct ResultDef {
    name: String,
    binders: Vec<String>,
    args: Vec<String>,
}

impl ResultDef {
    fn application(&self) -> String {
        if self.args.is_empty() {
            self.name.clone()
        } else {
            format!("{} {}", self.name, self.args.join(" "))
        }
    }
}

fn parse_result_defs(funs: &str) -> Vec<ResultDef> {
    let mut defs = Vec::new();
    let lines = funs.lines().collect::<Vec<_>>();
    let mut idx = 0;
    while idx < lines.len() {
        let line = lines[idx].trim_start();
        if !line.starts_with("def ") {
            idx += 1;
            continue;
        }

        let mut header = String::from(line);
        idx += 1;
        while idx < lines.len() && !header.contains(":=") {
            header.push('\n');
            header.push_str(lines[idx]);
            idx += 1;
        }

        if let Some(def) = parse_result_def_header(&header) {
            defs.push(def);
        }
    }
    defs
}

fn parse_result_def_header(header: &str) -> Option<ResultDef> {
    let header = header.trim_start();
    let after_def = header.strip_prefix("def ")?;
    let name_end = after_def.find(char::is_whitespace)?;
    let name = after_def[..name_end].to_string();
    let rest = &after_def[name_end..];
    let body_assignment = top_level_body_assignment(rest).unwrap_or(rest.len());
    let header_before_body = &rest[..body_assignment];
    let return_colon = top_level_return_colon(header_before_body)?;
    let (params, ret) = header_before_body.split_at(return_colon);
    if !ret.contains("Result") {
        return None;
    }

    let binders = extract_binders(params);
    let args = binders.iter().flat_map(|binder| binder_arg_names(binder)).collect();
    Some(ResultDef { name, binders, args })
}

fn top_level_body_assignment(input: &str) -> Option<usize> {
    let mut depth = 0usize;
    let mut chars = input.char_indices().peekable();
    while let Some((idx, ch)) = chars.next() {
        match ch {
            '(' | '{' | '[' => depth += 1,
            ')' | '}' | ']' => depth = depth.saturating_sub(1),
            ':' if depth == 0 && chars.peek().is_some_and(|(_, next)| *next == '=') => {
                return Some(idx);
            }
            _ => {}
        }
    }
    None
}

fn top_level_return_colon(input: &str) -> Option<usize> {
    let mut depth = 0usize;
    for (idx, ch) in input.char_indices() {
        match ch {
            '(' | '{' | '[' => depth += 1,
            ')' | '}' | ']' => depth = depth.saturating_sub(1),
            ':' if depth == 0 => return Some(idx),
            _ => {}
        }
    }
    None
}

fn extract_binders(input: &str) -> Vec<String> {
    let mut binders = Vec::new();
    let mut start = None;
    let mut depth = 0usize;
    let mut opener = '\0';
    for (idx, ch) in input.char_indices() {
        match ch {
            '(' | '{' => {
                if depth == 0 {
                    start = Some(idx);
                    opener = ch;
                }
                depth += 1;
            }
            ')' if opener == '(' => {
                depth = depth.saturating_sub(1);
                if depth == 0 {
                    if let Some(start) = start.take() {
                        binders.push(input[start..=idx].trim().replace('\n', " "));
                    }
                }
            }
            '}' if opener == '{' => {
                depth = depth.saturating_sub(1);
                if depth == 0 {
                    if let Some(start) = start.take() {
                        binders.push(input[start..=idx].trim().replace('\n', " "));
                    }
                }
            }
            _ => {}
        }
    }
    binders
}

fn binder_arg_names(binder: &str) -> Vec<String> {
    let inner = binder.trim().trim_start_matches(['(', '{']).trim_end_matches([')', '}']).trim();
    let before_colon = inner.split(':').next().unwrap_or(inner);
    before_colon.split_whitespace().filter(|name| *name != "_").map(str::to_string).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_single_line_result_def() {
        let funs = r#"
namespace demo

def gate.is_open (gate : gate.Gate) : Result Bool := do
  ok gate.«open»

end demo
"#;

        assert_eq!(
            parse_result_defs(funs),
            vec![ResultDef {
                name: "gate.is_open".into(),
                binders: vec!["(gate : gate.Gate)".into()],
                args: vec!["gate".into()],
            }]
        );
    }

    #[test]
    fn parses_multiline_result_def_with_default_arg() {
        let header = r#"def gate.choose_count
  (primary : Std.U32) (fallback : Std.U32) (use_primary : Bool)
  (h : fallback.val ≠ 42 := by scalar_tac) :
  Result Std.U32
  := do"#;

        assert_eq!(
            parse_result_def_header(header),
            Some(ResultDef {
                name: "gate.choose_count".into(),
                binders: vec![
                    "(primary : Std.U32)".into(),
                    "(fallback : Std.U32)".into(),
                    "(use_primary : Bool)".into(),
                    "(h : fallback.val ≠ 42 := by scalar_tac)".into(),
                ],
                args: vec!["primary".into(), "fallback".into(), "use_primary".into(), "h".into()],
            })
        );
    }

    #[test]
    fn ignores_non_result_defs() {
        let funs = r#"
namespace demo

def U32.Insts.CoreFmtDisplay : core.fmt.Display Std.U32 := {
  fmt := core.fmt.num.imp.DisplayU32.fmt
}

end demo
"#;

        assert!(parse_result_defs(funs).is_empty());
    }

    #[test]
    fn emits_default_soundness_module() {
        let funs = r#"
namespace demo

def f (x : Std.U32) : Result Std.U32 := do
  ok x

end demo
"#;

        let generated = default_soundness_module("Demo", funs).unwrap();

        assert!(generated.contains("import Demo.Funs"));
        assert!(generated.contains("namespace demo"));
        assert!(generated.contains("theorem anneal_default_soundness_0 (x : Std.U32) :"));
        assert!(generated.contains("⊢ₛ wp⟦f x⟧ post⟨fun _ => ⌜True⌝,"));
        assert!(generated.contains("cases h : f x <;> simp [WP.wp, PredTrans.apply, h]"));
    }
}
