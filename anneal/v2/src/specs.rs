//! Generation of Anneal specification Lean files.
//!
//! This module renders user-provided pure Lean snippets into the structural
//! Lean declarations Anneal owns. It does not parse the snippet contents.

use anyhow::Context as _;
use std::collections::HashMap;

use charon_lib::ast::{
    Body, FunDecl, FunDeclId, GenericParams, Local, RefKind, TraitDeclId, TraitDeclRef, Ty, TyKind,
    TypeDeclId, TypeId,
};

#[derive(Debug, thiserror::Error)]
pub enum Error {
    #[error("missing {kind} declaration {index} in LLBC")]
    MissingDecl { kind: &'static str, index: usize },
    #[error("`#[anneal::{annotation}]` Lean generation is not implemented yet for `{path}`")]
    UnsupportedAnnotation { annotation: &'static str, path: String },
    #[error("generic `{path}` is not supported by this Lean generation unit yet")]
    UnsupportedGenerics { path: String },
    #[error("missing argument name for argument {index} of `{path}`")]
    MissingArgumentName { path: String, index: usize },
    #[error("argument metadata for `{path}` has {names} name(s), but LLBC has {inputs} input(s)")]
    ArgumentNameCountMismatch { path: String, names: usize, inputs: usize },
    #[error(transparent)]
    Name(#[from] crate::names::Error),
    #[error(transparent)]
    Type(#[from] crate::lean_types::Error),
}

pub fn write_specs(
    roots: &crate::resolve::LockedRoots<'_>,
    annotated_artifacts: &[crate::annotations::AnnotatedArtifact],
) -> anyhow::Result<Vec<std::path::PathBuf>> {
    annotated_artifacts
        .iter()
        .filter(|artifact| !artifact.items.is_empty())
        .map(|artifact| write_artifact_specs(roots, artifact))
        .collect()
}

fn write_artifact_specs(
    roots: &crate::resolve::LockedRoots<'_>,
    artifact: &crate::annotations::AnnotatedArtifact,
) -> anyhow::Result<std::path::PathBuf> {
    let llbc_path = artifact.artifact.llbc_path(roots);
    let file = std::fs::File::open(&llbc_path)
        .with_context(|| format!("failed to open LLBC artifact `{}`", llbc_path.display()))?;
    let crate_data: charon_lib::export::CrateData = serde_json::from_reader(file)
        .with_context(|| format!("failed to parse LLBC artifact `{}`", llbc_path.display()))?;
    let code = render_artifact(&crate_data.translated, artifact).with_context(|| {
        format!("failed to generate Specs.lean for `{}`", artifact.artifact.llbc_file_name())
    })?;

    let output_dir = roots.lean_generated_root().join(artifact.artifact.artifact_slug());
    std::fs::create_dir_all(&output_dir)
        .with_context(|| format!("failed to create `{}`", output_dir.display()))?;
    let path = output_dir.join("Specs.lean");
    std::fs::write(&path, code).with_context(|| format!("failed to write `{}`", path.display()))?;
    Ok(path)
}

fn render_artifact(
    krate: &charon_lib::ast::TranslatedCrate,
    artifact: &crate::annotations::AnnotatedArtifact,
) -> Result<String, Error> {
    let slug = artifact.artifact.artifact_slug();
    let mut out = String::new();
    out.push_str("-- This file is automatically generated by Anneal.\n");
    out.push_str("-- Do not edit manually.\n\n");
    out.push_str("import Anneal\n");
    out.push_str("import Aeneas.Std.Scalar.Core\n");
    out.push_str(&format!("import {slug}.Funs\n"));
    out.push_str(&format!("import {slug}.Types\n\n"));
    out.push_str("set_option linter.dupNamespace false\n");
    out.push_str("set_option linter.unusedVariables false\n");
    out.push_str("open Aeneas Aeneas.Std Result\n\n");
    out.push_str("noncomputable section\n\n");
    out.push_str("inject_builtins\n\n");

    let crate_namespace = crate::names::crate_namespace(krate);
    out.push_str(&format!("namespace {crate_namespace}\n\n"));
    for item in &artifact.items {
        render_item(krate, item, &mut out)?;
        out.push('\n');
    }
    out.push_str(&format!("end {crate_namespace}\n"));
    Ok(out)
}

fn render_item(
    krate: &charon_lib::ast::TranslatedCrate,
    item: &crate::annotations::AnnotatedItem,
    out: &mut String,
) -> Result<(), Error> {
    match &item.body {
        crate::annotations::AnnotationBody::TypeInvariant(body) => {
            let type_id = TypeDeclId::from_usize(item.item_id.index);
            let ty = krate
                .type_decls
                .get(type_id)
                .ok_or(Error::MissingDecl { kind: "type", index: item.item_id.index })?;
            let generics = lean_generics(krate, &ty.generics, &item.path.join("::"))?;
            let path = crate::names::item_path(krate, &ty.item_meta.name)?;
            render_type_invariant(&path, &generics, body, out);
        }
        crate::annotations::AnnotationBody::TraitInvariant(body) => {
            let trait_id = TraitDeclId::from_usize(item.item_id.index);
            let tr = krate
                .trait_decls
                .get(trait_id)
                .ok_or(Error::MissingDecl { kind: "trait", index: item.item_id.index })?;
            let generics = lean_trait_generics(krate, &tr.generics, &item.path.join("::"))?;
            let path = crate::names::item_path(krate, &tr.item_meta.name)?;
            render_trait_invariant(&path, &generics, body, out);
        }
        crate::annotations::AnnotationBody::Function(function) => {
            let fun_id = FunDeclId::from_usize(item.item_id.index);
            let fun = krate
                .fun_decls
                .get(fun_id)
                .ok_or(Error::MissingDecl { kind: "function", index: item.item_id.index })?;
            let spec = function_spec(krate, fun, item, function)?;
            render_function(&spec, out);
        }
        crate::annotations::AnnotationBody::ImplInvariant(_) => {
            return Err(Error::UnsupportedAnnotation {
                annotation: "impl_invariant",
                path: item.path.join("::"),
            });
        }
    }
    Ok(())
}

#[derive(Debug)]
struct FunctionArg {
    name: String,
    lean_type: String,
    is_mut_ref: bool,
}

#[derive(Debug)]
struct FunctionSpec<'a> {
    path: crate::names::LeanItemPath,
    generics: LeanGenerics,
    args: Vec<FunctionArg>,
    return_type: Option<String>,
    annotation: &'a crate::annotations::FunctionAnnotation,
}

impl FunctionSpec<'_> {
    fn mut_args(&self) -> impl Iterator<Item = &FunctionArg> {
        self.args.iter().filter(|arg| arg.is_mut_ref)
    }

    fn aeneas_name(&self) -> String {
        self.path.aeneas_name()
    }

    fn fully_qualified_aeneas_name(&self) -> String {
        format!("_root_.{}", self.aeneas_name())
    }
}

fn function_spec<'a>(
    krate: &charon_lib::ast::TranslatedCrate,
    fun: &FunDecl,
    item: &crate::annotations::AnnotatedItem,
    annotation: &'a crate::annotations::FunctionAnnotation,
) -> Result<FunctionSpec<'a>, Error> {
    let path = item.path.join("::");
    let generics = lean_generics(krate, &fun.generics, &path)?;
    let item_path = crate::names::item_path(krate, &fun.item_meta.name)?;
    let args = function_args(krate, fun, item)?;
    let return_type = if is_unit_type(&fun.signature.output) {
        None
    } else {
        Some(crate::lean_types::render_type_with_generics(
            krate,
            &fun.generics,
            &fun.signature.output,
        )?)
    };
    Ok(FunctionSpec { path: item_path, generics, args, return_type, annotation })
}

fn function_args(
    krate: &charon_lib::ast::TranslatedCrate,
    fun: &FunDecl,
    item: &crate::annotations::AnnotatedItem,
) -> Result<Vec<FunctionArg>, Error> {
    let path = item.path.join("::");
    let metadata_names = item.annotation.argument_names.as_deref();
    if let Some(names) = metadata_names
        && names.len() != fun.signature.inputs.len()
    {
        return Err(Error::ArgumentNameCountMismatch {
            path,
            names: names.len(),
            inputs: fun.signature.inputs.len(),
        });
    }

    let input_locals = body_input_locals(&fun.body);
    if let Some(locals) = &input_locals
        && locals.len() != fun.signature.inputs.len()
    {
        return Err(Error::ArgumentNameCountMismatch {
            path,
            names: locals.len(),
            inputs: fun.signature.inputs.len(),
        });
    }

    fun.signature
        .inputs
        .iter()
        .enumerate()
        .map(|(index, signature_ty)| {
            let local = input_locals.as_ref().and_then(|locals| locals.get(index).copied());
            let name = local
                .and_then(|local| local.name.as_deref())
                .or_else(|| metadata_names.and_then(|names| names.get(index).map(String::as_str)))
                .ok_or_else(|| Error::MissingArgumentName { path: path.clone(), index })?;
            let ty = local.map(|local| &local.ty).unwrap_or(signature_ty);
            Ok(FunctionArg {
                name: crate::names::lean_identifier(name),
                lean_type: crate::lean_types::render_type_with_generics(krate, &fun.generics, ty)?,
                is_mut_ref: is_mut_ref(ty),
            })
        })
        .collect()
}

#[derive(Debug, Clone, Default, PartialEq, Eq)]
struct LeanGenerics {
    type_params: Vec<String>,
    const_params: Vec<LeanConstGeneric>,
    trait_dicts: Vec<LeanTraitDict>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
struct LeanConstGeneric {
    name: String,
    lean_type: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
struct LeanTraitDict {
    name: String,
    lean_type: String,
}

fn lean_generics(
    krate: &charon_lib::ast::TranslatedCrate,
    params: &GenericParams,
    path: &str,
) -> Result<LeanGenerics, Error> {
    if !params.trait_type_constraints.is_empty() {
        return Err(Error::UnsupportedGenerics { path: path.to_string() });
    }
    Ok(LeanGenerics {
        type_params: params
            .types
            .iter()
            .map(|param| crate::names::lean_identifier(&param.name))
            .collect(),
        const_params: params
            .const_generics
            .iter()
            .map(|param| {
                Ok(LeanConstGeneric {
                    name: crate::names::lean_identifier(&param.name),
                    lean_type: crate::lean_types::render_type_with_generics(
                        krate, params, &param.ty,
                    )?,
                })
            })
            .collect::<Result<Vec<_>, Error>>()?,
        trait_dicts: lean_trait_dicts(krate, params, path)?,
    })
}

fn lean_trait_dicts(
    krate: &charon_lib::ast::TranslatedCrate,
    params: &GenericParams,
    path: &str,
) -> Result<Vec<LeanTraitDict>, Error> {
    let mut used_names = HashMap::<String, ()>::new();
    params
        .trait_clauses
        .iter()
        .map(|clause| {
            if !clause.trait_.regions.is_empty() {
                return Err(Error::UnsupportedGenerics { path: path.to_string() });
            }
            let trait_ref = &clause.trait_.skip_binder;
            if !trait_ref.generics.trait_refs.is_empty() {
                return Err(Error::UnsupportedGenerics { path: path.to_string() });
            }
            let trait_decl = krate
                .trait_decls
                .get(trait_ref.id)
                .ok_or(Error::MissingDecl { kind: "trait", index: trait_ref.id.index() })?;
            let trait_path = crate::names::item_path(krate, &trait_decl.item_meta.name)?;
            let name = format!("{}Inst", trait_path.item);
            if used_names.insert(name.clone(), ()).is_some() {
                return Err(Error::UnsupportedGenerics { path: path.to_string() });
            }
            Ok(LeanTraitDict {
                name,
                lean_type: trait_dict_type(krate, params, &trait_path, trait_ref)?,
            })
        })
        .collect()
}

fn trait_dict_type(
    krate: &charon_lib::ast::TranslatedCrate,
    params: &GenericParams,
    path: &crate::names::LeanItemPath,
    trait_ref: &TraitDeclRef,
) -> Result<String, Error> {
    let mut parts = vec![path.item.clone()];
    parts.extend(crate::lean_types::render_generic_args_with_generics(
        krate,
        params,
        &trait_ref.generics,
    )?);
    Ok(parts.join(" "))
}

fn lean_trait_generics(
    krate: &charon_lib::ast::TranslatedCrate,
    params: &GenericParams,
    path: &str,
) -> Result<LeanGenerics, Error> {
    let mut generics = lean_generics(krate, params, path)?;
    if generics.type_params.first().map(String::as_str) == Some("Self") {
        generics.type_params.remove(0);
    }
    Ok(generics)
}

fn body_input_locals(body: &Body) -> Option<Vec<&Local>> {
    match body {
        Body::Structured(body) => {
            Some(body.locals.locals.iter().skip(1).take(body.locals.arg_count).collect())
        }
        Body::Unstructured(body) => {
            Some(body.locals.locals.iter().skip(1).take(body.locals.arg_count).collect())
        }
        _ => None,
    }
}

fn is_mut_ref(ty: &Ty) -> bool {
    matches!(ty.0.inner(), TyKind::Ref(_, _, RefKind::Mut))
}

fn is_unit_type(ty: &Ty) -> bool {
    match ty.0.inner() {
        TyKind::Adt(type_ref) => {
            matches!(&type_ref.id, TypeId::Tuple) && type_ref.generics.types.is_empty()
        }
        _ => false,
    }
}

fn render_function(spec: &FunctionSpec<'_>, out: &mut String) {
    render_namespace_open(&spec.path, out);
    render_context(&spec.annotation.context, out);
    render_function_pre(spec, out);
    render_function_post(spec, out);
    render_function_spec(spec, out);
    render_namespace_close(&spec.path, out);
}

fn render_function_pre(spec: &FunctionSpec<'_>, out: &mut String) {
    if !function_has_pre(spec) {
        return;
    }
    out.push_str("structure Pre");
    push_generic_binders(out, &spec.generics);
    push_arg_binders(out, &spec.args);
    out.push_str(" : Prop where\n");
    for arg in &spec.args {
        let field = format!("h_{}_is_valid", arg.name);
        out.push_str(&format!(
            "  {field} : Anneal.IsValid.isValid {} := by verify_is_valid {field} {}\n",
            arg.name,
            spec.fully_qualified_aeneas_name()
        ));
    }
    for fragment in &spec.annotation.requires {
        let field = fragment.name.as_deref().unwrap_or("h_anon");
        out.push_str(&format!("  {field} : "));
        push_field_type(out, &fragment.lean);
        out.push_str(&format!(
            " := by verify_user_bound {field} {}\n",
            spec.fully_qualified_aeneas_name()
        ));
    }
    out.push('\n');
}

fn render_function_post(spec: &FunctionSpec<'_>, out: &mut String) {
    out.push_str("structure Post");
    push_generic_binders(out, &spec.generics);
    push_arg_binders(out, &spec.args);
    if let Some(return_type) = &spec.return_type {
        out.push_str(&format!(" (ret : {return_type})"));
    }
    for arg in spec.mut_args() {
        out.push_str(&format!(" ({}' : {})", arg.name, arg.lean_type));
    }
    out.push_str(" : Prop where\n");

    if spec.return_type.is_some() {
        out.push_str(&format!(
            "  h_ret_is_valid : Anneal.IsValid.isValid ret := by verify_is_valid h_ret_is_valid {}\n",
            spec.fully_qualified_aeneas_name()
        ));
    }
    for arg in spec.mut_args() {
        let field = format!("h_{}'_is_valid", arg.name);
        out.push_str(&format!(
            "  {field} : Anneal.IsValid.isValid {}' := by verify_is_valid {field} {}\n",
            arg.name,
            spec.fully_qualified_aeneas_name()
        ));
    }
    for fragment in &spec.annotation.ensures {
        let field = fragment.name.as_deref().unwrap_or("h_anon");
        out.push_str(&format!("  {field} : "));
        push_field_type(out, &fragment.lean);
        out.push_str(&format!(
            " := by verify_user_bound {field} {}\n",
            spec.fully_qualified_aeneas_name()
        ));
    }
    out.push('\n');
}

fn render_function_spec(spec: &FunctionSpec<'_>, out: &mut String) {
    match spec.annotation.kind {
        crate::annotations::FunctionAnnotationKind::Spec => {
            render_function_theorem("theorem", spec, out);
            out.push_str(" := by\n");
            render_function_proof(spec, out);
        }
        crate::annotations::FunctionAnnotationKind::UnsafeAxiom => {
            render_function_theorem("axiom", spec, out);
            out.push('\n');
        }
    }
}

fn render_function_theorem(kind: &str, spec: &FunctionSpec<'_>, out: &mut String) {
    out.push_str(&format!("{kind} spec"));
    push_generic_binders(out, &spec.generics);
    push_arg_binders(out, &spec.args);
    if function_has_pre(spec) {
        out.push_str(" (h_req : Pre");
        for arg in function_context_arg_names(spec) {
            out.push_str(&format!(" {arg}"));
        }
        out.push(')');
    }
    out.push_str(" :\n");
    out.push_str(&format!("  Aeneas.Std.WP.spec ({})", function_call(spec)));
    out.push_str(" (fun ret_ =>");
    if let Some(lhs) = ret_destructure_lhs(spec) {
        out.push_str(&format!("\n    let {lhs} := ret_\n    "));
    } else {
        out.push(' ');
    }
    out.push_str("Post");
    for arg in function_context_arg_names(spec) {
        out.push_str(&format!(" {arg}"));
    }
    if spec.return_type.is_some() {
        out.push_str(if spec.mut_args().next().is_some() { " ret" } else { " ret_" });
    }
    for arg in spec.mut_args() {
        out.push_str(&format!(" {}'", arg.name));
    }
    out.push(')');
}

fn render_function_proof(spec: &FunctionSpec<'_>, out: &mut String) {
    let proofs = proof_map(spec);
    out.push_str("  apply Anneal.wp_prove_orthogonal\n");
    out.push_str("  · ");
    if let Some(progress) = proofs.get("h_progress") {
        push_proof_fragment(out, progress, "    ");
    } else {
        out.push_str(&format!(
            "eval_progress \"Missing orthogonal progress proof. The function progress verification was not automatically solvable.\" {}\n",
            spec.fully_qualified_aeneas_name()
        ));
    }
    out.push_str(&format!("  · rintro {} h_returns\n", intro_pattern(spec)));
    if function_has_pre(spec) {
        let fields = pre_field_names(spec);
        if !fields.is_empty() {
            out.push_str(&format!("    rcases h_req with ⟨{}⟩\n", fields.join(", ")));
        }
    }
    out.push_str("    exact\n");
    for fragment in &spec.annotation.proof_context {
        render_lean_lines(&fragment.lean, "      ", out);
    }
    let fields = post_field_names(spec);
    if fields.is_empty() {
        out.push_str("      ⟨⟩\n");
    } else {
        out.push_str("      {\n");
        for field in fields {
            out.push_str(&format!("        {field} := by\n"));
            if let Some(proof) = proofs.get(field.as_str()) {
                render_lean_lines(proof, "          ", out);
            } else if field.starts_with("h_") && field.ends_with("_is_valid") {
                out.push_str(&format!(
                    "          verify_is_valid {field} {}\n",
                    spec.fully_qualified_aeneas_name()
                ));
            } else {
                out.push_str(&format!(
                    "          verify_user_bound {field} {}\n",
                    spec.fully_qualified_aeneas_name()
                ));
            }
        }
        out.push_str("      }\n");
    }
}

fn function_has_pre(spec: &FunctionSpec<'_>) -> bool {
    !spec.args.is_empty() || !spec.annotation.requires.is_empty()
}

fn push_arg_binders(out: &mut String, args: &[FunctionArg]) {
    for arg in args {
        out.push_str(&format!(" ({} : {})", arg.name, arg.lean_type));
    }
}

fn function_context_arg_names(spec: &FunctionSpec<'_>) -> Vec<String> {
    spec.generics
        .trait_dicts
        .iter()
        .map(|dict| dict.name.clone())
        .chain(spec.args.iter().map(|arg| arg.name.clone()))
        .collect()
}

fn function_call(spec: &FunctionSpec<'_>) -> String {
    let mut parts = vec![spec.path.item.clone()];
    parts.extend(spec.generics.type_params.iter().map(|param| format!("({param} := {param})")));
    parts.extend(
        spec.generics
            .const_params
            .iter()
            .map(|param| format!("({} := {})", param.name, param.name)),
    );
    parts.extend(spec.generics.trait_dicts.iter().map(|dict| dict.name.clone()));
    parts.extend(spec.args.iter().map(|arg| arg.name.clone()));
    parts.join(" ")
}

fn push_generic_binders(out: &mut String, generics: &LeanGenerics) {
    for param in &generics.type_params {
        out.push_str(&format!(" {{{param} : Type}}"));
    }
    for param in &generics.const_params {
        out.push_str(&format!(" {{{} : {}}}", param.name, param.lean_type));
    }
    for dict in &generics.trait_dicts {
        out.push_str(&format!(" ({} : {})", dict.name, dict.lean_type));
    }
}

fn ret_destructure_lhs(spec: &FunctionSpec<'_>) -> Option<String> {
    let mut_args = spec.mut_args().collect::<Vec<_>>();
    if mut_args.is_empty() {
        return None;
    }
    let vars = mut_args.iter().map(|arg| format!("{}'", arg.name)).collect::<Vec<_>>();
    if spec.return_type.is_some() {
        Some(format!("(ret, {})", vars.join(", ")))
    } else if vars.len() == 1 {
        Some(vars[0].clone())
    } else {
        Some(format!("({})", vars.join(", ")))
    }
}

fn intro_pattern(spec: &FunctionSpec<'_>) -> String {
    let mut_args = spec.mut_args().collect::<Vec<_>>();
    if mut_args.is_empty() {
        return "ret".to_string();
    }
    let vars = mut_args.iter().map(|arg| format!("{}'", arg.name)).collect::<Vec<_>>();
    if spec.return_type.is_some() {
        format!("⟨ret, {}⟩", vars.join(", "))
    } else if vars.len() == 1 {
        vars[0].clone()
    } else {
        format!("⟨{}⟩", vars.join(", "))
    }
}

fn pre_field_names(spec: &FunctionSpec<'_>) -> Vec<String> {
    spec.args
        .iter()
        .map(|arg| format!("h_{}_is_valid", arg.name))
        .chain(
            spec.annotation
                .requires
                .iter()
                .map(|fragment| fragment.name.clone().unwrap_or_else(|| "h_anon".to_string())),
        )
        .collect()
}

fn post_field_names(spec: &FunctionSpec<'_>) -> Vec<String> {
    let mut fields = Vec::new();
    if spec.return_type.is_some() {
        fields.push("h_ret_is_valid".to_string());
    }
    fields.extend(spec.mut_args().map(|arg| format!("h_{}'_is_valid", arg.name)));
    fields.extend(
        spec.annotation
            .ensures
            .iter()
            .map(|fragment| fragment.name.clone().unwrap_or_else(|| "h_anon".to_string())),
    );
    fields
}

fn proof_map<'a>(spec: &'a FunctionSpec<'_>) -> HashMap<&'a str, &'a str> {
    spec.annotation
        .proofs
        .iter()
        .filter_map(|fragment| Some((fragment.name.as_deref()?, fragment.lean.as_str())))
        .collect()
}

fn push_field_type(out: &mut String, lean: &str) {
    if lean.contains('\n') {
        out.push_str("(\n");
        render_lean_lines(lean, "    ", out);
        out.push_str("  )");
    } else {
        out.push_str(lean);
    }
}

fn push_proof_fragment(out: &mut String, proof: &str, continuation_indent: &str) {
    let mut lines = proof.lines();
    if let Some(first) = lines.next() {
        out.push_str(first);
        out.push('\n');
        for line in lines {
            out.push_str(continuation_indent);
            out.push_str(line);
            out.push('\n');
        }
    } else {
        out.push_str("sorry\n");
    }
}

fn render_lean_lines(lean: &str, indent: &str, out: &mut String) {
    for line in lean.lines() {
        out.push_str(indent);
        out.push_str(line);
        out.push('\n');
    }
}

fn render_type_invariant(
    path: &crate::names::LeanItemPath,
    generics: &LeanGenerics,
    body: &crate::annotations::TypeInvariantAnnotation,
    out: &mut String,
) {
    render_namespace_open(path, out);
    render_context(&body.context, out);
    out.push_str("instance");
    push_generic_binders(out, generics);
    out.push_str(&format!(" : Anneal.IsValid {} where\n", type_application(&path.item, generics)));
    out.push_str("  isValid self :=\n");
    render_fragments(&body.is_valid, "    ", out);
    render_namespace_close(path, out);
}

fn type_application(name: &str, generics: &LeanGenerics) -> String {
    let args = generic_argument_names(generics);
    if args.is_empty() { name.to_string() } else { format!("({name} {})", args.join(" ")) }
}

fn render_trait_invariant(
    path: &crate::names::LeanItemPath,
    generics: &LeanGenerics,
    body: &crate::annotations::TraitInvariantAnnotation,
    out: &mut String,
) {
    render_namespace_open(path, out);
    render_context(&body.context, out);
    out.push_str("class Safe (Self : Type)");
    push_generic_binders(out, generics);
    out.push_str(&format!(" (inst : {}) : Prop where\n", trait_application(&path.item, generics)));
    out.push_str("  isSafe :\n");
    render_fragments(&body.is_safe, "    ", out);
    render_namespace_close(path, out);
}

fn trait_application(name: &str, generics: &LeanGenerics) -> String {
    let mut args = vec!["Self".to_string()];
    args.extend(generic_argument_names(generics));
    format!("{name} {}", args.join(" "))
}

fn generic_argument_names(generics: &LeanGenerics) -> Vec<String> {
    generics
        .type_params
        .iter()
        .cloned()
        .chain(generics.const_params.iter().map(|param| param.name.clone()))
        .collect()
}

fn render_namespace_open(path: &crate::names::LeanItemPath, out: &mut String) {
    for segment in path.spec_namespace_segments() {
        out.push_str(&format!("namespace {segment}\n\n"));
    }
}

fn render_namespace_close(path: &crate::names::LeanItemPath, out: &mut String) {
    for segment in path.spec_namespace_segments().into_iter().rev() {
        out.push_str(&format!("\nend {segment}\n"));
    }
}

fn render_context(fragments: &[crate::annotations::LeanFragment], out: &mut String) {
    for fragment in fragments {
        push_with_trailing_newline(out, &fragment.lean);
    }
    if !fragments.is_empty() {
        out.push('\n');
    }
}

fn render_fragments(
    fragments: &[crate::annotations::LeanFragment],
    indent: &str,
    out: &mut String,
) {
    if fragments.is_empty() {
        out.push_str(indent);
        out.push_str("True\n");
        return;
    }
    for fragment in fragments {
        for line in fragment.lean.lines() {
            out.push_str(indent);
            out.push_str(line);
            out.push('\n');
        }
    }
}

fn push_with_trailing_newline(out: &mut String, lean: &str) {
    out.push_str(lean);
    if !lean.ends_with('\n') {
        out.push('\n');
    }
}

