use crate::annotations::{AnnotatedArtifact, AnnotatedItem, AnnotationBody, FunctionAnnotation, FunctionAnnotationKind, LeanFragment, TypeInvariantAnnotation, TraitInvariantAnnotation};
use charon_lib::export::CrateData;
use charon_lib::ast::*;
use std::fmt::Write as _;

pub struct GeneratedCode {
    pub code: String,
    pub mappings: Vec<SourceMapping>,
}

#[derive(serde::Serialize, serde::Deserialize, Debug, Clone)]
pub struct SourceMapping {}

pub fn generate_artifact(
    annotated: &AnnotatedArtifact,
    crate_data: &CrateData,
) -> anyhow::Result<GeneratedCode> {
    let mut out = String::new();
    let slug = annotated.artifact.artifact_slug();

    writeln!(out, "-- THIS FILE WAS AUTOMATICALLY GENERATED BY ANNEAL")?;
    writeln!(out, "import Aeneas")?;
    writeln!(out, "import Anneal")?;
    writeln!(out, "import {slug}.Types")?;
    writeln!(out, "import {slug}.Funs")?;

    // Check if we need FunsExternal
    let mut has_external = false;
    for item in &annotated.items {
        if let AnnotationBody::Function(func_body) = &item.body {
            if func_body.kind == FunctionAnnotationKind::UnsafeAxiom {
                has_external = true;
                break;
            }
        }
    }
    if has_external {
        writeln!(out, "import {slug}.FunsExternal")?;
    }

    writeln!(out, "open Aeneas Aeneas.Std Result ControlFlow Error Anneal")?;
    writeln!(out)?;

    let package_ns = annotated.artifact.name.package_name.as_str().replace('-', "_");
    writeln!(out, "namespace {package_ns}")?;
    writeln!(out)?;

    for item in &annotated.items {
        match &item.body {
            AnnotationBody::Function(func_body) => {
                generate_function(&mut out, item, func_body, &package_ns, crate_data)?;
            }
            AnnotationBody::TypeInvariant(type_body) => {
                generate_type(&mut out, item, type_body, &package_ns, crate_data)?;
            }
            AnnotationBody::TraitInvariant(trait_body) => {
                generate_trait(&mut out, item, trait_body, &package_ns, crate_data)?;
            }
            _ => {}
        }
    }

    writeln!(out, "end {package_ns}")?;

    Ok(GeneratedCode { code: out, mappings: vec![] })
}

fn generate_function(
    out: &mut String,
    item: &AnnotatedItem,
    body: &FunctionAnnotation,
    package_ns: &str,
    crate_data: &CrateData,
) -> anyhow::Result<()> {
    // Find the FunDecl in crate_data to get the signature.
    let fun_decl = find_fun_decl(&item.path, crate_data)
        .ok_or_else(|| anyhow::anyhow!("failed to find FunDecl for path {:?}", item.path))?;

    let lean_fun_name = get_lean_function_name(fun_decl, crate_data);

    // Get argument names.
    let arg_names = item.annotation.argument_names.as_ref().ok_or_else(|| {
        anyhow::anyhow!("missing argument names in annotation for {:?}", item.path)
    })?;

    if fun_decl.signature.inputs.len() != arg_names.len() {
        log::warn!(
            "Argument names count ({}) does not match signature inputs count ({}) for {:?}",
            arg_names.len(),
            fun_decl.signature.inputs.len(),
            item.path
        );
    }

    // Identify mutable references.
    let mut mut_ref_indices = Vec::new();
    for (i, ty) in fun_decl.signature.inputs.iter().enumerate() {
        if is_mut_ref(ty) {
            mut_ref_indices.push(i);
        }
    }

    let fully_qualified_fnc = format!("_root_.{package_ns}.{lean_fun_name}");

    let has_return_value = !is_unit_return(&fun_decl.signature.output, crate_data);
    let has_pre = !body.requires.is_empty() || !arg_names.is_empty();
    let has_post = !body.ensures.is_empty() || has_return_value || !mut_ref_indices.is_empty();

    if has_pre {
        generate_pre_struct(out, &lean_fun_name, &fully_qualified_fnc, arg_names, &fun_decl.signature.inputs, &body.requires, &mut_ref_indices, crate_data)?;
    }

    if has_post {
        generate_post_struct(out, &lean_fun_name, &fully_qualified_fnc, arg_names, &fun_decl.signature.inputs, &fun_decl.signature.output, &body.ensures, &mut_ref_indices, crate_data)?;
    }

    generate_theorem(out, &lean_fun_name, &fully_qualified_fnc, arg_names, &fun_decl.signature.inputs, &fun_decl.signature.output, body, &mut_ref_indices, crate_data)?;

    Ok(())
}

fn find_fun_decl<'a>(
    path: &[String],
    crate_data: &'a CrateData,
) -> Option<&'a FunDecl> {
    crate_data.translated.fun_decls.iter().find(|fun| {
        let fun_path = fun_path_segments(&fun.item_meta.name);
        fun_path == path
    })
}

fn fun_path_segments(name: &Name) -> Vec<String> {
    name.name
        .iter()
        .map(|elem| match elem {
            PathElem::Ident(ident, _) => ident.clone(),
            PathElem::Impl(_) => "{impl}".to_string(),
            PathElem::Instantiated(_) => "{instantiated}".to_string(),
            PathElem::Target(target) => format!("{target:?}"),
        })
        .collect()
}

fn get_lean_function_name(fun_decl: &FunDecl, crate_data: &CrateData) -> String {
    let mut type_name = None;
    for elem in &fun_decl.item_meta.name.name {
        if let PathElem::Impl(impl_elem) = elem {
            if let ImplElem::Ty(binder) = impl_elem {
                type_name = Some(map_type_to_name_raw(&binder.skip_binder, crate_data));
            }
        }
    }

    let rust_name = fun_decl.item_meta.name.name.last().unwrap().as_ident().unwrap().0.clone();
    if let Some(tname) = type_name {
        format!("{tname}.{rust_name}")
    } else {
        rust_name
    }
}

fn map_type_to_name_raw(ty: &Ty, crate_data: &CrateData) -> String {
    match &**ty {
        TyKind::Adt(adt_ref) => {
            if let TypeId::Adt(adt_id) = adt_ref.id {
                let decl = crate_data.translated.type_decls.get(adt_id).unwrap();
                decl.item_meta.name.name.last().unwrap().as_ident().unwrap().0.clone()
            } else {
                "UnknownAdt".to_string()
            }
        }
        _ => "UnknownType".to_string(),
    }
}

fn is_mut_ref(ty: &Ty) -> bool {
    match &**ty {
        TyKind::Ref(_, _, RefKind::Mut) => true,
        _ => false,
    }
}

fn is_unit_return(ty: &Ty, crate_data: &CrateData) -> bool {
    map_type(ty, crate_data) == "Unit"
}

fn map_type(ty: &Ty, crate_data: &CrateData) -> String {
    match &**ty {
        TyKind::Adt(adt_ref) => {
            if let TypeId::Adt(adt_id) = adt_ref.id {
                if let Some(decl) = crate_data.translated.type_decls.get(adt_id) {
                    let name = decl.item_meta.name.name.last().unwrap().as_ident().unwrap().0.clone();
                    if decl.item_meta.is_local {
                        name
                    } else {
                        let path = fun_path_segments(&decl.item_meta.name);
                        if path.starts_with(&["core".to_string()]) {
                            format!("Std.{}", name)
                        } else {
                            name
                        }
                    }
                } else {
                    "UnknownAdt".to_string()
                }
            } else if adt_ref.id == TypeId::Tuple {
                let elems = &adt_ref.generics.types;
                if elems.is_empty() {
                    "Unit".to_string()
                } else {
                    let elems_lean = elems
                        .iter()
                        .map(|t| map_type(t, crate_data))
                        .collect::<Vec<_>>();
                    format!("({})", elems_lean.join(" × "))
                }
            } else {
                "UnsupportedAdtId".to_string()
            }
        }
        TyKind::Ref(_, inner, RefKind::Shared) => {
            map_type(inner, crate_data)
        }
        TyKind::Ref(_, inner, RefKind::Mut) => {
            map_type(inner, crate_data)
        }
        TyKind::RawPtr(elem_ty, ref_kind) => {
            let elem_lean = map_type(elem_ty, crate_data);
            match ref_kind {
                RefKind::Mut => format!("MutRawPtr {elem_lean}"),
                RefKind::Shared => format!("ConstRawPtr {elem_lean}"),
            }
        }
        TyKind::Literal(lit_ty) => {
            match *lit_ty {
                LiteralTy::Int(int_ty) => {
                    match int_ty {
                        IntTy::I32 => "Std.I32".to_string(),
                        IntTy::Isize => "Std.Isize".to_string(),
                        _ => format!("Std.{int_ty:?}"),
                    }
                }
                LiteralTy::UInt(uint_ty) => {
                    match uint_ty {
                        UIntTy::U32 => "Std.U32".to_string(),
                        UIntTy::Usize => "Std.Usize".to_string(),
                        _ => format!("Std.{uint_ty:?}"),
                    }
                }
                LiteralTy::Bool => "Bool".to_string(),
                LiteralTy::Char => "Char".to_string(),
                LiteralTy::Float(_) => "Float".to_string(),
            }
        }
        _ => format!("UnsupportedType({ty:?})"),
    }
}

fn generate_pre_struct(
    out: &mut String,
    fun_name: &str,
    fully_qualified_fnc: &str,
    arg_names: &[String],
    arg_types: &[Ty],
    requires: &[LeanFragment],
    mut_ref_indices: &[usize],
    crate_data: &CrateData,
) -> anyhow::Result<()> {
    let struct_name = format!("Pre_{}", fun_name.replace('.', "_"));
    write!(out, "structure {struct_name}")?;
    for (i, name) in arg_names.iter().enumerate() {
        let ty = &arg_types[i];
        let lean_ty = map_type(ty, crate_data);
        let name_to_use = if mut_ref_indices.contains(&i) {
            format!("old_{name}")
        } else {
            name.clone()
        };
        write!(out, " ({name_to_use} : {lean_ty})")?;
    }
    writeln!(out, " : Prop where")?;

    for (i, name) in arg_names.iter().enumerate() {
        let name_to_use = if mut_ref_indices.contains(&i) {
            format!("old_{name}")
        } else {
            name.clone()
        };
        writeln!(
            out,
            "  h_{name}_is_valid : Anneal.IsValid.isValid {name_to_use} := by verify_is_valid h_{name}_is_valid {fully_qualified_fnc}"
        )?;
    }

    for req in requires {
        let req_name = req.name.as_deref().unwrap_or("h_req");
        writeln!(
            out,
            "  {req_name} : {} := by verify_user_bound {req_name} {fully_qualified_fnc}",
            req.lean
        )?;
    }
    writeln!(out)?;
    Ok(())
}

fn generate_post_struct(
    out: &mut String,
    fun_name: &str,
    fully_qualified_fnc: &str,
    arg_names: &[String],
    arg_types: &[Ty],
    ret_type: &Ty,
    ensures: &[LeanFragment],
    mut_ref_indices: &[usize],
    crate_data: &CrateData,
) -> anyhow::Result<()> {
    let struct_name = format!("Post_{}", fun_name.replace('.', "_"));
    write!(out, "structure {struct_name}")?;
    for (i, name) in arg_names.iter().enumerate() {
        let ty = &arg_types[i];
        let lean_ty = map_type(ty, crate_data);
        let name_to_use = if mut_ref_indices.contains(&i) {
            format!("old_{name}")
        } else {
            name.clone()
        };
        write!(out, " ({name_to_use} : {lean_ty})")?;
    }
    let lean_ret_ty = map_type(ret_type, crate_data);
    write!(out, " (ret : {lean_ret_ty})")?;
    for &i in mut_ref_indices {
        let name = &arg_names[i];
        let ty = &arg_types[i];
        let lean_ty = map_type(ty, crate_data);
        write!(out, " ({name} : {lean_ty})")?;
    }
    writeln!(out, " : Prop where")?;

    let has_return_value = !is_unit_return(ret_type, crate_data);
    if has_return_value {
        writeln!(
            out,
            "  h_ret_is_valid : Anneal.IsValid.isValid ret := by verify_is_valid h_ret_is_valid {fully_qualified_fnc}"
        )?;
    }

    for &i in mut_ref_indices {
        let name = &arg_names[i];
        writeln!(
            out,
            "  h_{name}'_is_valid : Anneal.IsValid.isValid {name} := by verify_is_valid h_{name}'_is_valid {fully_qualified_fnc}"
        )?;
    }

    for ens in ensures {
        let ens_name = ens.name.as_deref().unwrap_or("h_ens");
        writeln!(
            out,
            "  {ens_name} : {} := by verify_user_bound {ens_name} {fully_qualified_fnc}",
            ens.lean
        )?;
    }
    writeln!(out)?;
    Ok(())
}

fn generate_theorem(
    out: &mut String,
    fun_name: &str,
    fully_qualified_fnc: &str,
    arg_names: &[String],
    arg_types: &[Ty],
    ret_type: &Ty,
    body: &FunctionAnnotation,
    mut_ref_indices: &[usize],
    crate_data: &CrateData,
) -> anyhow::Result<()> {
    let is_axiom = body.kind == FunctionAnnotationKind::UnsafeAxiom;
    let keyword = if is_axiom { "axiom" } else { "theorem" };
    let spec_name = format!("{}_spec", fun_name);

    write!(out, "{keyword} {spec_name}")?;

    for (i, name) in arg_names.iter().enumerate() {
        let ty = &arg_types[i];
        let lean_ty = map_type(ty, crate_data);
        let name_to_use = if mut_ref_indices.contains(&i) {
            format!("old_{name}")
        } else {
            name.clone()
        };
        write!(out, " ({name_to_use} : {lean_ty})")?;
    }

    let has_return_value = !is_unit_return(ret_type, crate_data);
    let has_pre = !body.requires.is_empty() || !arg_names.is_empty();
    let has_post = !body.ensures.is_empty() || has_return_value || !mut_ref_indices.is_empty();

    let fun_name_flat = fun_name.replace('.', "_");
    if has_pre {
        let pre_struct_name = format!("Pre_{}", fun_name_flat);
        write!(out, " (h_req : {pre_struct_name}")?;
        for (i, name) in arg_names.iter().enumerate() {
            let name_to_use = if mut_ref_indices.contains(&i) {
                format!("old_{name}")
            } else {
                name.clone()
            };
            write!(out, " {name_to_use}")?;
        }
        write!(out, ")")?;
    }

    write!(out, " :")?;

    write!(out, "\n  Aeneas.Std.WP.spec ({}", fun_name)?;
    for (i, name) in arg_names.iter().enumerate() {
        let name_to_use = if mut_ref_indices.contains(&i) {
            format!("old_{name}")
        } else {
            name.clone()
        };
        write!(out, " {name_to_use}")?;
    }
    write!(out, ")")?;

    if has_post {
        let post_struct_name = format!("Post_{}", fun_name_flat);
        write!(out, "\n    (fun ret_ => ")?;
        if mut_ref_indices.is_empty() {
            write!(out, "let ret := ret_;\n      {post_struct_name}")?;
            for (i, name) in arg_names.iter().enumerate() {
                let name_to_use = if mut_ref_indices.contains(&i) {
                    format!("old_{name}")
                } else {
                    name.clone()
                };
                write!(out, " {name_to_use}")?;
            }
            write!(out, " ret")?;
        } else {
            write!(out, "\n      let (ret, ")?;
            for (i, &idx) in mut_ref_indices.iter().enumerate() {
                if i > 0 {
                    write!(out, ", ")?;
                }
                write!(out, "{}", arg_names[idx])?;
            }
            write!(out, ") := ret_;\n      {post_struct_name}")?;
            for (i, name) in arg_names.iter().enumerate() {
                let name_to_use = if mut_ref_indices.contains(&i) {
                    format!("old_{name}")
                } else {
                    name.clone()
                };
                write!(out, " {name_to_use}")?;
            }
            write!(out, " ret")?;
            for &idx in mut_ref_indices {
                write!(out, " {}", arg_names[idx])?;
            }
        }
        write!(out, ")")?;
    } else {
        write!(out, "\n    (fun _ => True)")?;
    }

    if !is_axiom {
        writeln!(out, " := by")?;
        if has_pre {
            let mut req_fields = Vec::new();
            for name in arg_names {
                req_fields.push(format!("h_{name}_is_valid"));
            }
            for req in &body.requires {
                req_fields.push(req.name.clone().unwrap_or_else(|| "h_req".to_string()));
            }
            writeln!(out, "  rcases h_req with ⟨{}⟩", req_fields.join(", "))?;
        }

        if let Some(unnamed_proof) = body.proofs.iter().find(|p| p.name.is_none()) {
            for line in unnamed_proof.lean.lines() {
                writeln!(out, "  {}", line.trim())?;
            }
        } else {
            writeln!(out, "  unfold {fully_qualified_fnc}")?;
            writeln!(out, "  step*")?;

            for line in &body.proof_context {
                writeln!(out, "  {}", line.lean.trim())?;
            }

            if has_post {
                writeln!(out, "  exact {{")?;
                for proof in &body.proofs {
                    if let Some(name) = &proof.name {
                        if name == "h_progress" {
                            continue;
                        }
                        writeln!(out, "    {} := by", name)?;
                        for line in proof.lean.lines() {
                            writeln!(out, "      {}", line.trim())?;
                        }
                    }
                }
                writeln!(out, "  }}")?;
            } else {
                writeln!(out, "  trivial")?;
            }
        }
    } else {
        writeln!(out)?;
    }

    writeln!(out)?;
    Ok(())
}

fn find_type_decl<'a>(
    path: &[String],
    crate_data: &'a CrateData,
) -> Option<&'a TypeDecl> {
    crate_data.translated.type_decls.iter().find(|ty| {
        let ty_path = fun_path_segments(&ty.item_meta.name);
        ty_path == path
    })
}

fn find_trait_decl<'a>(
    path: &[String],
    crate_data: &'a CrateData,
) -> Option<&'a TraitDecl> {
    crate_data.translated.trait_decls.iter().find(|tr| {
        let tr_path = fun_path_segments(&tr.item_meta.name);
        tr_path == path
    })
}

fn generate_type(
    out: &mut String,
    item: &AnnotatedItem,
    body: &TypeInvariantAnnotation,
    _package_ns: &str,
    crate_data: &CrateData,
) -> anyhow::Result<()> {
    let ty_decl = find_type_decl(&item.path, crate_data)
        .ok_or_else(|| anyhow::anyhow!("failed to find TypeDecl for path {:?}", item.path))?;

    let type_name = ty_decl.item_meta.name.name.last().unwrap().as_ident().unwrap().0.clone();

    if !ty_decl.generics.types.is_empty() || !ty_decl.generics.const_generics.is_empty() {
        log::warn!("Generics are not supported yet for type invariants: {:?}", item.path);
        writeln!(out, "-- WARNING: Type invariant for generic type {} is not generated", type_name)?;
        return Ok(());
    }

    writeln!(out, "namespace {type_name}")?;
    writeln!(out)?;

    for line in &body.context {
        writeln!(out, "{}", line.lean.trim())?;
    }
    if !body.context.is_empty() {
        writeln!(out)?;
    }

    writeln!(out, "instance : Anneal.IsValid {type_name} where")?;
    if body.is_valid.is_empty() {
        writeln!(out, "  isValid self := True")?;
    } else {
        write!(out, "  isValid self :=")?;
        if body.is_valid.len() == 1 {
            writeln!(out, " {}", body.is_valid[0].lean.trim())?;
        } else {
            writeln!(out)?;
            for (i, clause) in body.is_valid.iter().enumerate() {
                if i > 0 {
                    writeln!(out, " ∧")?;
                }
                write!(out, "    ({})", clause.lean.trim())?;
            }
            writeln!(out)?;
        }
    }

    writeln!(out)?;
    writeln!(out, "end {type_name}")?;
    writeln!(out)?;

    Ok(())
}

fn generate_trait(
    out: &mut String,
    item: &AnnotatedItem,
    body: &TraitInvariantAnnotation,
    _package_ns: &str,
    crate_data: &CrateData,
) -> anyhow::Result<()> {
    let tr_decl = find_trait_decl(&item.path, crate_data)
        .ok_or_else(|| anyhow::anyhow!("failed to find TraitDecl for path {:?}", item.path))?;

    let trait_name = tr_decl.item_meta.name.name.last().unwrap().as_ident().unwrap().0.clone();

    // Filter out implicit `Self` parameter
    let generic_types = &tr_decl.generics.types;
    let has_non_self_types = if !generic_types.is_empty() && generic_types[0].name == "Self" {
        generic_types.len() > 1
    } else {
        !generic_types.is_empty()
    };

    if has_non_self_types || !tr_decl.generics.const_generics.is_empty() {
        log::warn!("Generics are not supported yet for trait invariants: {:?}", item.path);
        writeln!(out, "-- WARNING: Trait invariant for generic trait {} is not generated", trait_name)?;
        return Ok(());
    }

    writeln!(out, "namespace {trait_name}")?;
    writeln!(out)?;

    for line in &body.context {
        writeln!(out, "{}", line.lean.trim())?;
    }
    if !body.context.is_empty() {
        writeln!(out)?;
    }

    writeln!(out, "class Safe (Self : Type) (inst : {trait_name} Self) : Prop where")?;
    if body.is_safe.is_empty() {
        writeln!(out, "  isSafe : True")?;
    } else {
        write!(out, "  isSafe :")?;
        if body.is_safe.len() == 1 {
            writeln!(out, " {}", body.is_safe[0].lean.trim())?;
        } else {
            writeln!(out)?;
            for (i, clause) in body.is_safe.iter().enumerate() {
                if i > 0 {
                    writeln!(out, " ∧")?;
                }
                write!(out, "    ({})", clause.lean.trim())?;
            }
            writeln!(out)?;
        }
    }

    writeln!(out)?;
    writeln!(out, "end {trait_name}")?;
    writeln!(out)?;

    Ok(())
}
